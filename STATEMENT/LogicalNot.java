public class LogicalNot {
    public static void main(String[] args) {
        boolean a = true;
        boolean b = false;
        System.out.println("For logical NOT");
        System.out.println("Not(a) is ");
        System.out.println(!a);
        System.out.println("Not(b) is ");
        System.out.println(!b);
    }
}
